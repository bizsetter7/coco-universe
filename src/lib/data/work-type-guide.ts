// 슬러그로 지역 데이터 찾기
export function getRegionPayData(regionSlug: string): RegionPayData | undefined {
    return REGION_PAY_DATA.find(r =>
        r.slugs.some(s => s === regionSlug || regionSlug.includes(s) || s.includes(regionSlug))
    );
}

// 업종 슬러그 검증
export function isWorkTypeSlug(slug: string): slug is WorkTypeSlug {
    return WORK_TYPE_SLUGS.includes(slug as WorkTypeSlug);
}
