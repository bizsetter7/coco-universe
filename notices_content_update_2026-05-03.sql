## 4가지 광고 서비스

### 1. 추가광고 — 단순 노출권

구독 외 추가로 등록하시는 공고/광고입니다. 업체정보 광고리스트와 최신구인정보 섹션에 노출됩니다.

**가격**
- 1개월: 66,000원
- 3개월: 188,100원 (5% 할인)
- 6개월: 356,400원 (10% 할인)

적용 플랫폼: 코코알바 / 웨이터존 / 선수존 (가격 동일)

---

### 2. 점프(JUMP) — 광고 노출 우선순위 상승

광고 노출 순서를 일시적으로 끌어올리는 서비스입니다.

**중요**: 점프는 광고별로 따로 적용됩니다. 한 광고의 점프를 다른 광고에 사용할 수 없습니다.

무료 점프 (구독 시 자동 지급):
- 스페셜: 즉시 10회
- 디럭스: 즉시 30회
- 프리미엄: 즉시 30회 + 매일 +1회 자동 적립

광고 만료 시 잔여 점프는 소멸됩니다.

---

### 3. SOS — 회원 긴급 알림

선택한 지역/조건의 회원에게 긴급 모집 알림을 발송하는 서비스입니다.

**SOS 잔액은 계정에 포인트로 보존됩니다.** 광고가 만료되어도 사라지지 않으며 다른 광고에서 재사용 가능합니다.

---

### 4. 부스터 — 광고 시각 강조

광고를 더 눈에 띄게 만드는 시각 효과 옵션입니다.

효과 종류: 무빙 아이콘 (10종) / 형광펜 (10종) / 테두리 효과 (4종)

**가격** (각 효과별 동일)
- 30일: 30,000원
- 60일: 55,000원
- 90일: 70,000원

부스터는 광고 보유가 필수입니다. 광고 잔여 기간이 부스터 옵션보다 짧으면 일할로 차감됩니다.
광고 만료 시 부스터 효과도 함께 종료됩니다.

