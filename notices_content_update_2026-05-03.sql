## 자주 묻는 질문

**Q. 점프가 광고별로 따로 적용된다는 게 무슨 뜻인가요?**
A. 자동 광고와 추가광고는 각자 독립된 점프 잔액을 가집니다. 자동 광고의 점프를 추가광고에 사용하실 수 없습니다.

**Q. 광고가 끝나면 남은 점프나 부스터는 어떻게 되나요?**
A. 점프와 부스터는 광고 만료 시 소멸됩니다. SOS 포인트는 계정에 보존됩니다.

**Q. 추가광고와 구독은 어떻게 다른가요?**
A. 구독은 야사장에서 결제하며 자동 광고 노출이 포함됩니다. 추가광고는 각 플랫폼에서 직접 결제하는 단순 노출권입니다.

